"""score_blind.py: score the blind identification test. usage: python -I score_blind.py <pixelart_root> <guesses.json>"""
import json, os, sys, math
root, gpath = sys.argv[1], sys.argv[2]
key = json.load(open(os.path.join(root, "eval_key", "blind_key.json")))
meta = json.load(open(os.path.join(root, "out", "doodle_meta.json")))
classes = meta["classes"] if "classes" in meta else meta["CLASSES"]
G = json.load(open(gpath))
guesses = {str(g["cell"]): g for g in G["guesses"]}
assert sorted(guesses, key=int) == sorted(key, key=int) and len(key) == 36
cells, per = [], {c: {"n": 0, "correct": 0, "cells": []} for c in classes}
for k in sorted(key, key=int):
    t, g = key[k], guesses[k]
    assert t in classes and g["guess"] in classes, (k, t, g)
    ok = g["guess"] == t
    cells.append({"cell": int(k), "true": t, "guess": g["guess"], "correct": ok,
                  "confidence": g["confidence"], "recognizable": g["recognizable"]})
    per[t]["n"] += 1; per[t]["correct"] += ok; per[t]["cells"].append(int(k))
n = len(cells); c = sum(x["correct"] for x in cells)
# exact one-sided binomial tail P(X >= c) for X ~ Bin(36, 1/18)
p = 1 / 18
tail = sum(math.comb(n, i) * p**i * (1 - p)**(n - i) for i in range(c, n + 1))
# Wilson 95% interval
z = 1.959964; ph = c / n
den = 1 + z*z/n; mid = (ph + z*z/(2*n)) / den; hw = z * math.sqrt(ph*(1-ph)/n + z*z/(4*n*n)) / den
conf = [{"cell": x["cell"], "true": x["true"], "guess": x["guess"], "confidence": x["confidence"]}
        for x in cells if not x["correct"]]
pairs = {}
for x in conf: pairs.setdefault(f'{x["true"]} -> {x["guess"]}', []).append(x["cell"])
guess_counts = {}
for x in cells: guess_counts[x["guess"]] = guess_counts.get(x["guess"], 0) + 1
never_guessed = [cl for cl in classes if cl not in guess_counts]
recog = [x for x in cells if x["recognizable"]]
res = {
  "test": "TONER-1-V blind identification test",
  "method": "36 doodles (2 per class, shuffled, black, unlabeled) generated by the print job in Ghostscript at T 0.9; "
            "identified blind by an AI model that was not told the labels; not a human study. "
            "Top-1 accuracy: guess == true class.",
  "evaluator_input": "ps/blind_grid.png only",
  "n": n, "correct": c, "accuracy": round(c / n, 4),
  "accuracy_wilson95": [round(mid - hw, 4), round(mid + hw, 4)],
  "chance": round(1/18, 4), "chance_expected_correct": 2.0,
  "p_value_vs_chance_one_sided_binomial": tail,
  "per_class": {cl: {"n": v["n"], "correct": v["correct"], "accuracy": v["correct"] / v["n"], "cells": v["cells"]}
                for cl, v in per.items()},
  "classes_2_of_2": [cl for cl, v in per.items() if v["correct"] == 2],
  "classes_1_of_2": [cl for cl, v in per.items() if v["correct"] == 1],
  "classes_0_of_2": [cl for cl, v in per.items() if v["correct"] == 0],
  "flagged_recognizable": {"n": len(recog), "correct": sum(x["correct"] for x in recog)},
  "flagged_not_recognizable": {"n": n - len(recog), "correct": c - sum(x["correct"] for x in recog)},
  "mean_confidence_correct": round(sum(x["confidence"] for x in cells if x["correct"]) / max(c, 1), 3),
  "mean_confidence_wrong": round(sum(x["confidence"] for x in conf) / max(len(conf), 1), 3),
  "confusions": conf,
  "confusion_pairs": pairs,
  "guess_counts": guess_counts,
  "never_guessed": never_guessed,
  "cells": cells,
}
out = os.path.join(root, "eval_key", "blind_results.json")
json.dump(res, open(out, "w"), indent=1)
print(f"{c}/{n} = {c/n:.1%}  (Wilson 95% {mid-hw:.1%}-{mid+hw:.1%}; chance 5.6%, p = {tail:.2e})")
for k in ("classes_2_of_2", "classes_1_of_2", "classes_0_of_2"): print(k, res[k])
print("recognizable-flagged:", res["flagged_recognizable"], "not:", res["flagged_not_recognizable"])
print("conf correct/wrong:", res["mean_confidence_correct"], res["mean_confidence_wrong"])
print("never guessed:", never_guessed); print("guess counts:", guess_counts)
for kk, v in pairs.items(): print("  ", kk, v)
print("wrote", out)
