"""make_results_data.py: write results_data.ps for the blind-test results page.
Reads (all under <pixelart_root>):
  eval_key/blind_results.json   scored guesses (from score_blind.py)
  eval_key/blind_grid.log       the blind grid job's log: "D cell class seed v1 .. v64" per doodle
  out/doodle_meta.json          class names, to map guesses to class indices
Writes <out_ps>, which defines:
  /BGUESS [ class index of the evaluator's guess, cells 1..36 ]
  /BCONF  [ evaluator's stated confidence ]      /BRECOG [ evaluator's "recognizable" flag ]
  /BEXP   [ [ 64 patch values ] ... ]  the blind grid's patch tokens, so the job can check its own doodles
usage: python -I make_results_data.py <pixelart_root> <out_ps>"""
import json, os, sys

root, out = sys.argv[1], sys.argv[2]
res = json.load(open(os.path.join(root, "eval_key", "blind_results.json")))
meta = json.load(open(os.path.join(root, "out", "doodle_meta.json")))
classes = meta["classes"] if "classes" in meta else meta["CLASSES"]
cells = sorted(res["cells"], key=lambda c: c["cell"])
assert [c["cell"] for c in cells] == list(range(1, 37))

exp = {}
for line in open(os.path.join(root, "eval_key", "blind_grid.log")):
    if line.startswith("D "):
        f = line.split()
        k, cls, seed, pv = int(f[1]), int(f[2]), int(f[3]), [int(v) for v in f[4:]]
        assert len(pv) == 64 and all(0 <= v < 16 for v in pv)
        exp[k] = (cls, seed, pv)
assert sorted(exp) == list(range(1, 37))
for c in cells:                                   # the log's class must be the key's class
    assert classes[exp[c["cell"]][0]] == c["true"], c

with open(out, "w") as f:
    f.write("% TONER-1-V blind test results data (generated by results/src/make_results_data.py; do not edit)\n")
    f.write("% Guesses by an AI model that was not told the labels (eval_key/blind_guesses.json); not a human study.\n")
    f.write("/BGUESS [ " + " ".join(str(classes.index(c["guess"])) for c in cells) + " ] def\n")
    f.write("/BCONF [ " + " ".join(f'{c["confidence"]:g}' for c in cells) + " ] def\n")
    f.write("/BRECOG [ " + " ".join("true" if c["recognizable"] else "false" for c in cells) + " ] def\n")
    f.write("/BEXP [\n")
    for k in range(1, 37):
        f.write("  [ " + " ".join(map(str, exp[k][2])) + " ]\n")
    f.write("] def\n")
print("wrote", out)
